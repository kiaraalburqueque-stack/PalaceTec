import { test, expect } from '@playwright/test';

test('sprint 2: límite, apuesta, liquidación, historial, repetición y seguridad', async ({ page, request }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const suffix = Date.now();
  const email = `browser-${suffix}@example.com`;
  const password = 'Palace123!';
  await page.goto('/registro');
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('DNI', { exact: true }).fill(String(suffix).slice(-8));
  await page.getByLabel('Fecha de nacimiento').fill('2000-01-01');
  await page.getByLabel('Contraseña', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
  await expect(page.getByText('¡Cuenta creada!')).toBeVisible();
  await page.goto('/login');
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await page.getByRole('button', { name: 'Entrar a la sala' }).first().click();
  await expect(page.getByRole('button', { name: 'Apostar', exact: true })).toBeDisabled();
  await page.getByRole('link', { name: 'Mis límites', exact: true }).click();
  await page.getByLabel('Límite diario en CRD').fill('100');
  await page.getByRole('button', { name: 'Guardar límite' }).click();
  await expect(page.getByText(/Disponible: 100.00 CRD/)).toBeVisible();
  await page.goto('/ruleta/1');
  await expect(page.getByRole('button', { name: 'Apostar', exact: true })).toBeEnabled();
  await page.getByLabel('Tipo de apuesta:').selectOption('DOZEN');
  await page.getByLabel('Docena o columna').selectOption('1');
  await page.getByRole('button', { name: 'Apostar', exact: true }).click();
  await expect(page.getByText('¡Apuesta registrada correctamente!')).toBeVisible();
  expect((await request.post('http://localhost:8010/__e2e__/settle')).ok()).toBeTruthy();
  await expect(page.getByRole('list', { name: 'Resultados recientes' })).toContainText('12');
  await expect(page.getByRole('button', { name: 'Repetir conjunto anterior' })).toBeEnabled();
  await page.getByRole('button', { name: 'Repetir conjunto anterior' }).click();
  await expect(page.getByText('Conjunto anterior repetido correctamente.')).toBeVisible();
  await page.getByRole('link', { name: 'Mi historial', exact: true }).click();
  await expect(page.getByText('2 apuestas · Página 1')).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Ganada', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'Pendiente', exact: true })).toHaveCount(3);
  await page.context().clearCookies({ name: 'access_token' });
  await page.getByRole('link', { name: 'Mis estadísticas', exact: true }).click();
  await expect(page.locator('.stats-grid').getByText('20.00 CRD', { exact: true })).toBeVisible();
  expect((await page.context().cookies()).some((cookie) => cookie.name === 'access_token')).toBeTruthy();
  await page.goto('/perfil');
  await page.getByLabel('Nombres').fill('Sebastián');
  await page.getByLabel('Apellidos').fill('Prueba');
  await page.getByLabel('Teléfono').fill('+51 999999999');
  await page.getByRole('button', { name: 'Guardar perfil' }).click();
  await expect(page.getByText('Perfil actualizado correctamente.')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Nombres')).toHaveValue('Sebastián');
  await page.goto('/administracion/exclusiones');
  await expect(page.getByRole('heading', { name: 'Acceso restringido' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/ruleta/1');
  await expect(page.getByRole('button', { name: 'Apostar', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  expect((await page.locator('.round-panel').boundingBox()).width).toBeGreaterThan(300);
  expect((await page.locator('.wheel-panel').boundingBox()).width).toBeGreaterThan(300);
  await page.screenshot({ path: 'test-results/sprint2-mobile.png', fullPage: true });
  await page.goto('/perfil/seguridad');
  await page.getByLabel('Contraseña actual', { exact: true }).fill(password);
  await page.getByLabel('Nueva contraseña', { exact: true }).fill('Actualizada123!');
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('Actualizada123!');
  await page.getByRole('button', { name: 'Cambiar contraseña', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByText('Contraseña actualizada. Inicia sesión nuevamente.')).toBeVisible();
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill('Actualizada123!');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Juegos disponibles' })).toBeVisible();
  await page.getByRole('link', { name: 'Mis límites', exact: true }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirmar autoexclusión' }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByText(/Autoexclusión confirmada hasta/)).toBeVisible();
  expect(errors).toEqual([]);
});

test('sprint 2: recupera pausa y aviso de realidad tras recargar', async ({ page, request }) => {
  const suffix = Date.now() + 1;
  const email = `reality-${suffix}@example.com`;
  const csrf = await request.get('http://localhost:8010/api/v1/auth/csrf');
  const { csrfToken } = await csrf.json();
  await request.post('http://localhost:8010/api/v1/auth/register', { headers: { 'X-CSRFToken': csrfToken }, data: { email, dni: String(suffix).slice(-8), birth_date: '2000-01-01', password: 'Palace123!' } });
  await page.goto('/login');
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill('Palace123!');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Juegos disponibles' })).toBeVisible();
  await page.getByRole('link', { name: 'Mis límites', exact: true }).click();
  await page.getByLabel('Límite diario en CRD').fill('100');
  await page.getByRole('button', { name: 'Guardar límite' }).click();
  await expect(page.getByText(/Disponible: 100.00 CRD/)).toBeVisible();
  await request.post('http://localhost:8010/__e2e__/incident', { data: { email } });
  await request.post('http://localhost:8010/__e2e__/session-hour', { data: { email } });
  await page.reload();
  await expect(page.getByRole('dialog', { name: 'Tiempo de hacer una pausa' })).toBeVisible();
  await page.getByRole('button', { name: 'Continuar jugando' }).click();
  await page.getByRole('button', { name: 'Tomar pausa de 10 minutos' }).click();
  await expect(page.getByText(/Pausa activa/)).toBeVisible();
  await page.goto('/ruleta/1');
  await expect(page.getByText('Conexión: En vivo')).toBeVisible();
  await expect(page.getByText(/Cupo diario disponible: 100.00/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Apostar', exact: true })).toBeDisabled();
  await expect(page.getByRole('dialog', { name: 'Tiempo de hacer una pausa' })).toHaveCount(0);
});
